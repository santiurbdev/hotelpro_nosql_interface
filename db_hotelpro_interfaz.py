    def _filter_current_report(self, *_):
        if not self.report_tree or not self.report_tree.winfo_exists():
            return
        term = self.report_search_var.get().strip().lower()
        if term == tr("Buscar en el reporte...").lower():
            term = ""
        for item in self.report_tree.get_children():
            self.report_tree.delete(item)
        visible = 0
        for row in self.report_rows:
            if not term or term in " ".join(str(v) for v in row).lower():
                self.report_tree.insert(
                    "", "end", values=row,
                    tags=("even" if visible % 2 == 0 else "odd",),
                )
                visible += 1
        if self.report_status_label and self.report_status_label.winfo_exists():
            if LANGUAGE == "en":
                status = f"Showing {visible} of {len(self.report_rows)} records"
            else:
                status = f"Mostrando {visible} de {len(self.report_rows)} registros"
            self.report_status_label.configure(text=status)

    def _reload_current_report(self):
        if self.current_page == "report1":
            self.open_report_1()
        elif self.current_page == "report2":
            self.open_report_2()
        elif self.current_page == "report3":
            self.open_report_3()

    def _export_current_report(self):
        if not self.report_rows:
            messagebox.showwarning(
                "Sin información",
                "No hay registros disponibles para exportar.",
                parent=self.root,
            )
            return
        path = filedialog.asksaveasfilename(
            parent=self.root, defaultextension=".csv",
            filetypes=[(tr("Archivo CSV"), "*.csv")],
            initialfile=f"{self.current_page}_hotelpro.csv",
        )
        if not path: return
        try:
            visible_rows = []
            if self.report_tree and self.report_tree.winfo_exists():
                visible_ids = self.report_tree.get_children()
                visible_rows = [
                    self.report_tree.item(i, "values") for i in visible_ids
                ]
            with open(path, "w", newline="", encoding="utf-8-sig") as f:
                w = csv.writer(f)
                w.writerow(self.report_export_headers)
                w.writerows(visible_rows)
            messagebox.showinfo(
                "Exportación completada",
                f"El archivo se guardó correctamente:\n{path}",
                parent=self.root,
            )
        except Exception as exc:
            messagebox.showerror(
                "Error de exportación",
                f"No fue posible guardar el archivo.\n\n{exc}",
                parent=self.root,
            )

    def _run_report(self, pipeline, collection="reserva"):
        if not self.connect_database(show_error=True):
            return None
        try:
            return list(self.db[collection].aggregate(pipeline, maxTimeMS=15000))
        except Exception as exc:
            messagebox.showerror(
                "Error al consultar",
                f"No fue posible generar el reporte.\n\nDetalle: {exc}",
                parent=self.root,
            )
            return None

