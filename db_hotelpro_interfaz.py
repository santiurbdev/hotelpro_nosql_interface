    def open_validations(self):
        self._clear_page()
        self._build_header(
            "Reglas de negocio",
            "Validación de datos de reservas y habitaciones",
        )
        self._set_active_nav("validations")
        self._page_heading(
            "Validaciones del sistema",
            "Comprueba que los datos cumplan las reglas definidas para la operación hotelera.",
        )

        content = ctk.CTkFrame(self.page, fg_color="transparent")
        content.pack(fill="both", expand=True)

        reservation_card = self._card(content)
        reservation_card.pack(fill="x", pady=(0, 18))

        self._section_title(
            reservation_card, "01", "Validación de reserva",
            "Fechas de entrada y salida, y cantidad de huéspedes (1 a 6).",
        )

        ctk.CTkFrame(
            reservation_card, fg_color=COLORS["border"], height=1, corner_radius=0,
        ).pack(fill="x", padx=26, pady=(18, 0))

        reservation_form = ctk.CTkFrame(reservation_card, fg_color="transparent")
        reservation_form.pack(fill="x", padx=26, pady=(20, 8))

        arrival_var = ctk.StringVar()
        departure_var = ctk.StringVar()
        guests_var = ctk.StringVar()

        self._add_date_picker(reservation_form, "Fecha de entrada (AAAA-MM-DD)", arrival_var, 0)
        self._add_date_picker(reservation_form, "Fecha de salida (AAAA-MM-DD)", departure_var, 1)
        self._form_field(reservation_form, "Huéspedes (1-6)", guests_var, 0, 2, width=140)

        result_reservation = ctk.CTkLabel(
            reservation_card,
            text="Completa los campos y ejecuta la validación.",
            font=(FONT, 10), text_color=COLORS["muted"],
        )
        result_reservation.pack(anchor="w", padx=26, pady=(12, 0))

        def validate_reservation():
            try:
                arrival = datetime.strptime(arrival_var.get().strip(), "%Y-%m-%d").date()
                departure = datetime.strptime(departure_var.get().strip(), "%Y-%m-%d").date()
                guests = int(guests_var.get().strip())
                if departure <= arrival:
                    raise ValueError("La fecha de salida debe ser posterior a la fecha de entrada.")
                if not 1 <= guests <= 6:
                    raise ValueError("El número de huéspedes debe estar entre 1 y 6.")
                result_reservation.configure(
                    text="✓  Reserva válida. Los datos cumplen las reglas.",
                    text_color=COLORS["green"],
                )
            except ValueError as exc:
                result_reservation.configure(
                    text=f"✕  {tr(str(exc))}", text_color=COLORS["red"],
                )

        btn_row = ctk.CTkFrame(reservation_card, fg_color="transparent")
        btn_row.pack(fill="x", padx=26, pady=(16, 26))
        self._button(
            btn_row, "Validar reserva", validate_reservation, "primary",
            width=160, height=42,
        ).pack(side="left")

        room_card = self._card(content)
        room_card.pack(fill="x")

        self._section_title(
            room_card, "02", "Validación de habitación",
            "Tipo permitido y tarifa base mayor que cero.",
        )

        ctk.CTkFrame(
            room_card, fg_color=COLORS["border"], height=1, corner_radius=0,
        ).pack(fill="x", padx=26, pady=(18, 0))

        room_form = ctk.CTkFrame(room_card, fg_color="transparent")
        room_form.pack(fill="x", padx=26, pady=(20, 8))

        ctk.CTkLabel(
            room_form, text="Tipo de habitación",
            font=(FONT, 9, "bold"), text_color=COLORS["muted"],
        ).grid(row=0, column=0, sticky="w", padx=(0, 18))

        room_type = ctk.CTkOptionMenu(
            room_form,
            values=[tr(v) for v in ["sencilla", "doble", "familiar", "suite"]],
            font=(FONT, 11), width=200, height=42, corner_radius=10,
            fg_color=COLORS["surface_alt"],
            button_color=COLORS["navy"],
            button_hover_color=COLORS["navy_3"],
            text_color=COLORS["text"],
            dropdown_fg_color=COLORS["surface"],
            dropdown_text_color=COLORS["text"],
            dropdown_hover_color=COLORS["gold_soft"],
        )
        room_type.grid(row=1, column=0, sticky="w", padx=(0, 25), pady=(7, 0))

        rate_var = ctk.StringVar()
        self._form_field(room_form, "Tarifa base ($)", rate_var, 0, 1, width=220)

        result_room = ctk.CTkLabel(
            room_card,
            text="Selecciona un tipo e ingresa la tarifa base.",
            font=(FONT, 10), text_color=COLORS["muted"],
        )
        result_room.pack(anchor="w", padx=26, pady=(12, 0))

        def validate_room():
            allowed = {"sencilla", "doble", "familiar", "suite"}
            selected_type = room_type.get().strip().lower()
            if LANGUAGE == "en":
                selected_type = {
                    "single": "sencilla", "double": "doble",
                    "family": "familiar", "suite": "suite",
                }.get(selected_type, selected_type)
            try:
                rate = float(rate_var.get().strip().replace(",", "."))
                if selected_type not in allowed:
                    raise ValueError("Selecciona un tipo de habitación permitido.")
                if rate <= 0:
                    raise ValueError("La tarifa base debe ser mayor que cero.")
                result_room.configure(
                    text="✓  Habitación válida. Los datos cumplen las reglas.",
                    text_color=COLORS["green"],
                )
            except ValueError as exc:
                result_room.configure(
                    text=f"✕  {tr(str(exc))}", text_color=COLORS["red"],
                )

        btn_row2 = ctk.CTkFrame(room_card, fg_color="transparent")
        btn_row2.pack(fill="x", padx=26, pady=(16, 26))
        self._button(
            btn_row2, "Validar habitación", validate_room, "primary",
            width=180, height=42,
        ).pack(side="left")

    def _add_date_picker(self, parent, label, variable, column):
        cell = ctk.CTkFrame(parent, fg_color="transparent")
        cell.grid(row=0, column=column, sticky="w", padx=(0, 24), pady=4)

        ctk.CTkLabel(
            cell, text=label, font=(FONT, 9, "bold"),
            text_color=COLORS["muted"],
        ).pack(anchor="w")

        if DateEntry is not None:
            picker = DateEntry(
                cell, textvariable=variable, width=18,
                date_pattern="yyyy-mm-dd",
                locale=("en_US" if LANGUAGE == "en" else "es_ES"),
                background=COLORS["navy"][0], foreground=COLORS["surface"][0],
                bordercolor=COLORS["gold"][0],
                headersbackground=COLORS["navy"][0],
                headersforeground=COLORS["surface"][0],
                selectbackground=COLORS["gold"][0],
                selectforeground=COLORS["navy"][0],
                normalbackground=COLORS["surface"][0],
                normalforeground=COLORS["text"][0],
                weekendbackground=COLORS["surface_alt"][0],
                weekendforeground=COLORS["text"][0],
                othermonthbackground=COLORS["surface_alt"][0],
                othermonthforeground=COLORS["muted"][0],
                showweeknumbers=False, font=(FONT, 10),
            )
        else:
            picker = ctk.CTkEntry(
                cell, textvariable=variable, width=200, height=42,
                font=(FONT, 11), corner_radius=10,
                fg_color=COLORS["surface_alt"],
                border_color=COLORS["border"],
                text_color=COLORS["text"],
            )
        picker.pack(anchor="w", pady=(6, 0))
        return picker

    def _section_title(self, parent, number, title, description):
        heading = ctk.CTkFrame(parent, fg_color="transparent")
        heading.pack(fill="x", padx=26, pady=(24, 0))

        badge = ctk.CTkFrame(
            heading, fg_color=COLORS["gold_soft"],
            width=46, height=46, corner_radius=12,
        )
        badge.pack(side="left", padx=(0, 14))
        badge.pack_propagate(False)
        ctk.CTkLabel(
            badge, text=number, font=(FONT, 12, "bold"),
            text_color=COLORS["gold"],
        ).pack(expand=True)

        text = ctk.CTkFrame(heading, fg_color="transparent")
        text.pack(side="left", fill="x", expand=True)

        ctk.CTkLabel(
            text, text=title, font=(FONT, 15, "bold"),
            text_color=COLORS["text"],
        ).pack(anchor="w")
        ctk.CTkLabel(
            text, text=description, font=(FONT, 10),
            text_color=COLORS["muted"],
        ).pack(anchor="w", pady=(2, 0))

    def _form_field(self, parent, label, variable, row, column, width=200):
        cell = ctk.CTkFrame(parent, fg_color="transparent")
        cell.grid(row=row, column=column, sticky="w", padx=(0, 24), pady=4)

        ctk.CTkLabel(
            cell, text=label, font=(FONT, 9, "bold"),
            text_color=COLORS["muted"],
        ).pack(anchor="w")

        entry = ctk.CTkEntry(
            cell, textvariable=variable, width=width, height=42,
            font=(FONT, 11), corner_radius=10,
            fg_color=COLORS["surface_alt"],
            border_color=COLORS["border"],
            text_color=COLORS["text"],
        )
        entry.pack(anchor="w", pady=(6, 0))
        return entry

