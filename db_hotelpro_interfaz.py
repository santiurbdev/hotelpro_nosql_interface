_OriginalCTkLabel = ctk.CTkLabel


class _LocalizedCTkLabel(_OriginalCTkLabel):
    def __init__(self, *args, **kwargs):
        if "text" in kwargs:
            kwargs["text"] = tr(kwargs["text"])
        super().__init__(*args, **kwargs)

    def configure(self, *args, **kwargs):
        if "text" in kwargs:
            kwargs["text"] = tr(kwargs["text"])
        return super().configure(*args, **kwargs)

    config = configure


ctk.CTkLabel = _LocalizedCTkLabel

_OriginalCTkButton = ctk.CTkButton


class _LocalizedCTkButton(_OriginalCTkButton):
    def __init__(self, *args, **kwargs):
        if "text" in kwargs:
            kwargs["text"] = tr(kwargs["text"])
        super().__init__(*args, **kwargs)

    def configure(self, *args, **kwargs):
        if "text" in kwargs:
            kwargs["text"] = tr(kwargs["text"])
        return super().configure(*args, **kwargs)

    config = configure


ctk.CTkButton = _LocalizedCTkButton

_OriginalHeading = ttk.Treeview.heading


def _localized_heading(self, column, option=None, **kwargs):
    if "text" in kwargs:
        kwargs["text"] = tr(kwargs["text"])
    return _OriginalHeading(self, column, option, **kwargs)


ttk.Treeview.heading = _localized_heading

_original_showerror = messagebox.showerror
_original_showwarning = messagebox.showwarning
_original_showinfo = messagebox.showinfo


def _localized_dialog(original):
    def _show(title, message, **kwargs):
        return original(tr(title), tr(message), **kwargs)

    return _show


messagebox.showerror = _localized_dialog(_original_showerror)
messagebox.showwarning = _localized_dialog(_original_showwarning)
messagebox.showinfo = _localized_dialog(_original_showinfo)


