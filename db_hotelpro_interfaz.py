    def connect_database(self, show_error=False):
        try:
            if self.client is None:
                self.client = MongoClient(
                    self.mongo_uri,
                    serverSelectionTimeoutMS=2500,
                    connectTimeoutMS=2500,
                )
            self.client.admin.command("ping")
            self.db = self.client[self.database_name]
            self.db_connected = True
            self._refresh_connection_badge()
            return True
        except Exception as exc:
            self.db_connected = False
            self.db = None
            self._refresh_connection_badge()
            if show_error:
                messagebox.showerror(
                    "Conexión con MongoDB",
                    "No fue posible conectar con MongoDB.\n\n"
                    "Verifica que el servicio esté iniciado y que la "
                    "base de datos esté disponible.\n\n"
                    f"Detalle: {exc}",
                    parent=self.root,
                )
            return False

    def _refresh_connection_badge(self):
        if hasattr(self, "connection_badge") and self.connection_badge.winfo_exists():
            if self.db_connected:
                self.connection_badge.configure(
                    text="●  MongoDB conectado",
                    text_color=COLORS["green"],
                    fg_color=COLORS["green_soft"],
                )
            else:
                self.connection_badge.configure(
                    text="●  MongoDB desconectado",
                    text_color=COLORS["red"],
                    fg_color=COLORS["red_soft"],
                )

